#!/usr/bin/env python3
"""
Generate the ROM API tables of csim's CC13x2/CC26x2 stand-in ROM.

The chip's ROM holds driverlib, and firmware calls it through a table of
tables: ROM_API_TABLE at 0x10000180 holds, per driverlib module, a pointer to
that module's function table, and every ROM_<Name> macro in driverlib/rom.h is
"cast ROM_API_<MODULE>_TABLE[n] to <signature> and call it".  This script
reads those macros and writes a C file with

  - one wrapper per ROM_<Name>, with the signature taken from the macro's
    cast, that calls the driverlib function of the same name (so functions
    driverlib implements as static inline in a header get a body too), and
  - the module tables and ROM_API_TABLE itself, placed by the linker script
    at the address rom.h gives.

A slot rom.h does not name points at rom_unimplemented(), so a firmware
call into a ROM function this file does not supply is reported on stderr
with its call site and the CPU parks in a bkpt loop there, instead of
running into whatever happens to be at the slot.

Usage: gen-rom-tables.py <driverlib/rom.h> <out.c>
"""
import re
import sys

MODULE_RE = re.compile(
    r"#define\s+ROM_API_(\w+)_TABLE\s+\(\(uint32_t\s*\*\)\s*\(ROM_API_TABLE\[(\d+)\]\)\)")
ENTRY_RE = re.compile(
    r"#define\s+ROM_(\w+)\s*\\\s*\(\((.+?)\(\*\)\s*\((.*?)\)\)\s*\\\s*"
    r"ROM_API_(\w+)_TABLE\[(\d+)\]\)", re.S)


def split_params(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    out.append(cur.strip())
    return out


def param_name(p):
    m = re.search(r"(\w+)\s*(\[\s*\])?$", p)
    if not m:
        raise SystemExit("cannot name parameter: %r" % p)
    return m.group(1)


def main():
    src = open(sys.argv[1]).read()
    modules = {m.group(1): int(m.group(2)) for m in MODULE_RE.finditer(src)}
    entries = []
    for m in ENTRY_RE.finditer(src):
        name, ret, params, module, idx = m.groups()
        if module not in modules:
            raise SystemExit("ROM_%s names unknown module %s" % (name, module))
        entries.append((name, " ".join(ret.split()), split_params(params),
                        module, int(idx)))
    if not entries:
        raise SystemExit("no ROM_ entries found in %s" % sys.argv[1])

    tables = {}
    for name, _, _, module, idx in entries:
        slots = tables.setdefault(module, {})
        if idx in slots:
            raise SystemExit("ROM_%s and ROM_%s share %s[%d]" %
                             (slots[idx], name, module, idx))
        slots[idx] = name

    o = []
    o.append("/* Generated by tools/cc13x2-rom/gen-rom-tables.py from driverlib/rom.h."
             " Do not edit. */")
    o.append("#include \"rom-includes.h\"")
    o.append("")
    o.append("void rom_unimplemented(void);")
    o.append("")
    for name, ret, params, _, _ in entries:
        args = ", ".join(param_name(p) for p in params)
        decl = ", ".join(params) if params else "void"
        call = "%s(%s)" % (name, args)
        body = ("%s;" % call) if ret == "void" else ("return %s;" % call)
        o.append("static %s rom_%s(%s) { %s }" % (ret, name, decl, body))
    o.append("")
    for module in sorted(tables, key=lambda k: modules[k]):
        slots = tables[module]
        n = max(slots) + 1
        o.append("__attribute__((section(\".rom_tables\"), used))")
        o.append("static const void *const rom_api_%s[%d] = {" % (module.lower(), n))
        for i in range(n):
            target = ("rom_%s" % slots[i]) if i in slots else "rom_unimplemented"
            o.append("    [%d] = (const void *)%s," % (i, target))
        o.append("};")
    n = max(modules.values()) + 1
    o.append("")
    o.append("/* ROM_API_TABLE: [0] = ROM_VERSION, then one module table per index. */")
    o.append("__attribute__((section(\".rom_api_table\"), used))")
    o.append("const void *const rom_api_table[%d] = {" % n)
    o.append("    [0] = (const void *)CSIM_ROM_VERSION,")
    by_idx = {v: k for k, v in modules.items()}
    for i in range(1, n):
        if i in by_idx and by_idx[i] in tables:
            o.append("    [%d] = rom_api_%s," % (i, by_idx[i].lower()))
        else:
            o.append("    [%d] = 0,  /* no module in rom.h */" % i)
    o.append("};")
    open(sys.argv[2], "w").write("\n".join(o) + "\n")
    print("%d ROM functions in %d module tables" % (len(entries), len(tables)))


if __name__ == "__main__":
    main()
