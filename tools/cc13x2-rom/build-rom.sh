#!/usr/bin/env bash
#
# Build csim's CC13x2/CC26x2 stand-in ROM and write it out as a C array.
#
# The firmware Contiki-NG builds for the CC13x2/CC26x2 links TI's prebuilt
# driverlib, which calls into the chip's ROM through the tables at
# 0x10000048 (HAPI) and 0x10000180 (ROM_API_TABLE).  csim does not ship
# TI's ROM.  It builds one from the BSD-licensed driverlib sources in the
# SimpleLink SDK instead: the same functions, compiled for flash-free
# execution (DRIVERLIB_NOROM), with the tables at the addresses rom.h names.
#
# Usage: tools/cc13x2-rom/build-rom.sh [--contiki-dir DIR] [OUT.c]
#   default OUT.c: src/arm/cc13x2_rom_image.c
#   default DIR:   $CONTIKI_DIR, else ../contiki-ng (needs the
#                  coresdk_cc13xx_cc26xx submodule checked out)
#   ROM_ELF=path   also keep the linked ROM ELF (addr2line a ROM PC)
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
CSIM_DIR="$(cd "$HERE/../.." && pwd)"
CONTIKI_DIR="${CONTIKI_DIR:-$CSIM_DIR/../contiki-ng}"
OUT="$CSIM_DIR/src/arm/cc13x2_rom_image.c"
while [ $# -gt 0 ]; do
    case "$1" in
        --contiki-dir) CONTIKI_DIR="$2"; shift 2 ;;
        -h|--help) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) OUT="$1"; shift ;;
    esac
done
SDK="$CONTIKI_DIR/arch/cpu/simplelink-cc13xx-cc26xx/lib/coresdk_cc13xx_cc26xx"
DEV="$SDK/source/ti/devices/cc13x2_cc26x2"
[ -f "$DEV/driverlib/rom.h" ] || {
    echo "error: $DEV/driverlib/rom.h not found (CONTIKI_DIR / submodule?)" >&2; exit 1; }

CC=${CC:-arm-none-eabi-gcc}
OBJCOPY=${OBJCOPY:-arm-none-eabi-objcopy}
TMP="$(mktemp -d "${TMPDIR:-/tmp}/cc13x2-rom.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

CFLAGS="-mcpu=cortex-m4 -mthumb -mfloat-abi=soft -Os -std=gnu99
        -ffunction-sections -fdata-sections -ffreestanding -fno-common
        -fno-tree-loop-distribute-patterns
        -DDRIVERLIB_NOROM -DDeviceFamily_CC13X2
        -I$DEV -I$HERE -Wall -Wno-unused-function"

python3 "$HERE/gen-rom-tables.py" "$DEV/driverlib/rom.h" "$TMP/rom-tables.c"

OBJS=()
for src in "$DEV"/driverlib/*.c "$HERE/hapi.c" "$HERE/rom-libc.c" "$TMP/rom-tables.c"; do
    obj="$TMP/$(basename "$src" .c).o"
    # shellcheck disable=SC2086
    $CC $CFLAGS -c "$src" -o "$obj"
    OBJS+=("$obj")
done
# shellcheck disable=SC2086
$CC -mcpu=cortex-m4 -mthumb -mfloat-abi=soft -nostdlib -Wl,--gc-sections \
    -T "$HERE/rom.ld" -Wl,-Map,"$TMP/rom.map" "${OBJS[@]}" -lgcc -o "$TMP/rom.elf"
$OBJCOPY -O binary "$TMP/rom.elf" "$TMP/rom.bin"
# ROM_ELF=path keeps the linked ELF, to map a ROM PC to its driverlib function.
[ -n "${ROM_ELF:-}" ] && cp "$TMP/rom.elf" "$ROM_ELF"

SDK_VER="$(git -C "$SDK" describe --always --dirty 2>/dev/null || echo unknown)"
python3 - "$TMP/rom.bin" "$OUT" "$SDK_VER" <<'EOF'
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by tools/cc13x2-rom/build-rom.sh. Do not edit.\n"
            " *\n"
            " * csim's CC13x2/CC26x2 stand-in ROM, mapped at 0x10000000: driverlib\n"
            " * (BSD-3-Clause, Texas Instruments) from the SimpleLink core SDK,\n"
            " * coresdk_cc13xx_cc26xx %s, behind the ROM API tables rom.h calls.\n"
            " */\n" % sys.argv[3])
    f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("const size_t cc13x2_rom_image_size = %d;\n" % len(data))
    f.write("const uint8_t cc13x2_rom_image[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")
print("ROM image: %d bytes -> %s" % (len(data), sys.argv[2]))
EOF
